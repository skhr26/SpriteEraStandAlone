/**
 * Helper to fetch a story by ID.
 * If not found directly, falls back to the Tata SUV story or generates
 * default structured slides based on fallback data.
 */
export function getWebStoryById(storyId) {
  if (!storyId) return webStorySlidesData[0];

  const clean = storyId.toLowerCase().trim();
  const found = webStorySlidesData.find(
    (story) => 
      story.id.toLowerCase() === clean ||
      (story.slug && story.slug.toLowerCase() === clean) ||
      (story.alias && story.alias.toLowerCase() === clean)
  );

  if (found) return found;

  // If ID matches tata or auto or work-is-underway, return Tata story
  if (clean.includes('tata') || clean.includes('suv') || clean.includes('work-is-underway') || clean === 'ws-13') {
    return webStorySlidesData[0];
  }

  // Return the first story as a safe, beautifully styled fallback
  return webStorySlidesData[0];
}

/**
 * Returns all available stories list
 */
export function getAllWebStories() {
  return webStorySlidesData;
}

export default webStorySlidesData;
